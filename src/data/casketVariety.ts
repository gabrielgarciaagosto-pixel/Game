const METAL = {
  brass: ['#f4e2a8', '#c6a15a', '#6e5420'] as [string, string, string],
  silver: ['#f8fafc', '#c5d0da', '#6a7884'] as [string, string, string],
  iron: ['#d0cbc4', '#6e6862', '#2a2622'] as [string, string, string],
  wood: ['#f0d7a6', '#c4924c', '#6a4520'] as [string, string, string],
};

type Stock = 'always' | 'rare' | 'ultra';

interface Spec {
  id: string;
  name: string;
  material: CasketMaterial;
  silhouette: CasketSilhouette;
  finish: string;
  hardwareLabel: string;
  blurb: string;
  cost: number;
  prestige: number;
  rep: number;
  stock: Stock;
  hour?: number;
  dark?: boolean;
  tone: Tone;
  lining: string;
  thread?: string;
  embroidery: CasketEmbroidery;
  hardware: CasketHardwareKind;
  bar: keyof typeof METAL;
  plates: 2 | 3 | 4;
  plate: CasketPlateShape;
  texture: CasketTexture;
  molding: CasketMolding;
  carving: CasketCarving;
  metal?: boolean;
  gloss?: number;
}

function dressOf(s: Spec): CasketDress {
  const bar = METAL[s.bar];
  return {
    lining: s.lining,
    thread: s.thread ?? '#6d8a48',
    embroidery: s.embroidery,
    hardware: s.hardware,
    plates: s.plates,
    plate: s.plate,
    texture: s.texture,
    molding: s.molding,
    carving: s.carving,
    metal: s.metal ?? false,
    gloss: s.gloss ?? (s.texture === 'lacquer' ? 0.85 : s.texture === 'matte' ? 0.12 : 0.45),
    ...s.tone,
    bar,
    lug: bar,
  };
}

function entry(s: Spec): CasketCatalogEntry {
  const dress = dressOf(s);
  return {
    id: s.id,
    name: s.name,
    material: s.material,
    silhouette: s.silhouette,
    finish: s.finish,
    hardware: s.hardwareLabel,
    blurb: s.blurb,
    cost: s.cost,
    resaleValue: Math.round(s.cost * 2.2),
    prestigeBonus: s.prestige,
    reputationRequired: s.rep,
    palette: {
      body: dress.front,
      bodyDeep: dress.frontDeep,
      highlight: dress.topHi,
      lining: dress.lining,
      hardware: dress.bar[1],
      trim: dress.gap,
    },
    dress,
  };
}

